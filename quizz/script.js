class QuizSoundPlayer {
	constructor() {
		this.currentAudio = null;
		this.muted = localStorage.getItem('halacha_quiz_muted') === '1';
	}

	toggleMute() {
		this.muted = !this.muted;
		localStorage.setItem('halacha_quiz_muted', this.muted ? '1' : '0');
		if (this.muted) {
			this.stop();
		}
		return this.muted;
	}

	stop() {
		if (this.currentAudio) {
			this.currentAudio.pause();
			this.currentAudio.currentTime = 0;
			this.currentAudio = null;
		}
	}

	playEffect(isCorrect) {
		if (this.muted) return;
		this.stop();

		const fileName = isCorrect ? 'right.effect.mp3' : 'wrong.effect.mp3';
		const candidateUrls = [
			`../assets/audio/${fileName}`,
			`/assets/audio/${fileName}`
		];

		this.tryPlayUrls(candidateUrls, 0);
	}

	tryPlayUrls(urls, index) {
		if (index >= urls.length) return;
		const audio = new Audio(urls[index]);
		this.currentAudio = audio;

		const handleError = () => {
			if (this.currentAudio === audio) {
				this.currentAudio = null;
			}
			this.tryPlayUrls(urls, index + 1);
		};

		audio.addEventListener('error', handleError, { once: true });
		audio.play().catch(handleError);
	}
}

class HalachaQuizApp {
	constructor(questions) {
		this.allQuestions = questions;
		this.sound = new QuizSoundPlayer();

		this.score = parseInt(localStorage.getItem('halacha_quiz_score') || '0', 10);
		this.streak = parseInt(localStorage.getItem('halacha_quiz_streak') || '0', 10);
		this.round = parseInt(localStorage.getItem('halacha_quiz_round') || '1', 10);

		this.deck = [];
		this.currentIndex = 0;
		this.isLocked = false;

		this.cacheElements();
		this.bindEvents();
		this.updateMuteButton();
		this.startNewRound(false);
	}

	cacheElements() {
		this.scoreVal = document.getElementById('score-val');
		this.streakVal = document.getElementById('streak-val');
		this.roundVal = document.getElementById('round-val');
		this.progressVal = document.getElementById('progress-val');

		this.simanBadge = document.getElementById('siman-badge');
		this.melachaBadge = document.getElementById('melacha-badge');
		this.seifBadge = document.getElementById('seif-badge');
		this.questionImageWrap = document.getElementById('question-image-wrap');
		this.questionImage = document.getElementById('question-image');
		this.questionText = document.getElementById('question-text');

		this.btnMutar = document.getElementById('btn-mutar');
		this.btnAsur = document.getElementById('btn-asur');

		this.feedbackPanel = document.getElementById('feedback-panel');
		this.feedbackBadge = document.getElementById('feedback-badge');
		this.correctAnswerPill = document.getElementById('correct-answer-pill');
		this.explanationText = document.getElementById('explanation-text');
		this.nextBtn = document.getElementById('next-btn');

		this.muteBtn = document.getElementById('mute-btn');
		this.muteIcon = document.getElementById('mute-icon');
		this.resetScoreBtn = document.getElementById('reset-score-btn');
	}

	bindEvents() {
		this.btnMutar.addEventListener('click', () => this.handleAnswer('מותר'));
		this.btnAsur.addEventListener('click', () => this.handleAnswer('אסור'));
		this.nextBtn.addEventListener('click', () => this.nextQuestion());

		this.muteBtn.addEventListener('click', () => {
			this.sound.toggleMute();
			this.updateMuteButton();
		});

		this.resetScoreBtn.addEventListener('click', () => {
			this.score = 0;
			this.streak = 0;
			this.round = 1;
			this.saveStats();
			this.startNewRound(false);
		});

		document.addEventListener('keydown', (e) => {
			if (e.key === 'Enter' || e.key === ' ') {
				if (this.isLocked && !this.feedbackPanel.hidden && document.activeElement !== this.nextBtn) {
					e.preventDefault();
					this.nextQuestion();
				}
			} else if (!this.isLocked) {
				if (e.key === 'ArrowRight' || e.key === '1') {
					this.handleAnswer('מותר');
				} else if (e.key === 'ArrowLeft' || e.key === '2') {
					this.handleAnswer('אסור');
				}
			}
		});
	}

	updateMuteButton() {
		this.muteIcon.textContent = this.sound.muted ? '🔇' : '🔊';
		this.muteBtn.setAttribute('aria-pressed', this.sound.muted ? 'true' : 'false');
	}

	shuffle(array) {
		const copy = array.slice();
		for (let i = copy.length - 1; i > 0; i--) {
			const j = Math.floor(Math.random() * (i + 1));
			[copy[i], copy[j]] = [copy[j], copy[i]];
		}
		return copy;
	}

	startNewRound(incrementRound = true) {
		if (incrementRound) {
			this.round += 1;
			this.saveStats();
		}
		this.deck = this.shuffle(this.allQuestions);
		this.currentIndex = 0;
		this.renderCurrentQuestion();
	}

	saveStats() {
		localStorage.setItem('halacha_quiz_score', String(this.score));
		localStorage.setItem('halacha_quiz_streak', String(this.streak));
		localStorage.setItem('halacha_quiz_round', String(this.round));
	}

	updateHeaderStats() {
		this.scoreVal.textContent = String(this.score);
		this.streakVal.textContent = String(this.streak);
		this.roundVal.textContent = String(this.round);
		this.progressVal.textContent = `${this.currentIndex + 1}/${this.deck.length}`;
	}

	renderCurrentQuestion() {
		this.isLocked = false;
		const q = this.deck[this.currentIndex];

		this.simanBadge.textContent = q.siman;
		this.melachaBadge.textContent = q.melacha;
		this.seifBadge.textContent = q.seif;
		this.questionText.textContent = q.question;

		if (q.image) {
			this.questionImage.src = q.image;
			this.questionImageWrap.hidden = false;
		} else {
			this.questionImage.removeAttribute('src');
			this.questionImageWrap.hidden = true;
		}

		[this.btnMutar, this.btnAsur].forEach((btn) => {
			btn.disabled = false;
			btn.classList.remove('is-dimmed', 'is-correct-choice', 'is-wrong-choice', 'is-correct-reveal');
		});

		this.feedbackPanel.hidden = true;
		this.updateHeaderStats();
	}

	handleAnswer(userChoice) {
		if (this.isLocked) return;
		this.isLocked = true;

		const q = this.deck[this.currentIndex];
		const isCorrect = userChoice === q.answer;

		this.btnMutar.disabled = true;
		this.btnAsur.disabled = true;

		const chosenBtn = userChoice === 'מותר' ? this.btnMutar : this.btnAsur;
		const otherBtn = userChoice === 'מותר' ? this.btnAsur : this.btnMutar;

		if (isCorrect) {
			this.score += 1;
			this.streak += 1;
			chosenBtn.classList.add('is-correct-choice');
			otherBtn.classList.add('is-dimmed');

			this.feedbackBadge.textContent = '✓ תְּשׁוּבָה נְכוֹנָה!';
			this.feedbackBadge.className = 'feedback-status-badge status-correct';
		} else {
			this.streak = 0;
			chosenBtn.classList.add('is-wrong-choice');
			otherBtn.classList.add('is-correct-reveal');

			this.feedbackBadge.textContent = '✕ לֹא מְדֻיָּק';
			this.feedbackBadge.className = 'feedback-status-badge status-wrong';
		}

		this.saveStats();
		this.updateHeaderStats();
		this.sound.playEffect(isCorrect);

		const vocalizedAnswer = q.answer === 'מותר' ? 'מֻתָּר' : 'אָסוּר';
		this.correctAnswerPill.textContent = `הַהֲלָכָה: ${vocalizedAnswer}`;
		this.explanationText.textContent = q.explanation;
		this.feedbackPanel.hidden = false;
		this.nextBtn.focus();
	}

	nextQuestion() {
		if (this.currentIndex + 1 < this.deck.length) {
			this.currentIndex += 1;
			this.renderCurrentQuestion();
		} else {
			this.startNewRound(true);
		}
	}
}

document.addEventListener('DOMContentLoaded', () => {
	new HalachaQuizApp(QUESTIONS);
});
